import type { GuideAudience } from "../claims";
import type { Archetype, Categoria, HubGroup, ToolId } from "../manifests";

/** Estado editorial com que o pacote faz nascer cada guia. */
export type EstadoInicial = "Revisto" | "Em revisão";
export type TipoGuia = "Procedimento" | "Decisão" | "Referência";
export type RiscoManutencao = "alta" | "media" | "baixa";
export type Prioridade = "P1" | "P2" | "P3";

export interface GuiaExpansao {
  slug: string;
  titulo: string;
  /** Subtítulo editorial (uma frase). É a descrição usada no índice. */
  dek: string;
  seccao: string;
  hub: HubGroup;
  tipo: TipoGuia;
  arquetipo: Archetype;
  publico: Categoria;
  audiencias: GuideAudience[];
  tempo: number;
  prioridade: Prioridade;
  /** Onda de redação (1 a 4). A ordem existe: os primeiros de cada cluster
      criam o contexto de ligação interna para os seguintes. */
  onda: 1 | 2 | 3 | 4;
  risco: RiscoManutencao;
  estado: EstadoInicial;
  exigeRevisaoEspecializada: boolean;
  metaDescription: string;
  palavrasChave: string[];
  relacionados: string[];
  ferramentas: ToolId[];
  /** Responde à pergunta do título sem remeter para o corpo. Vive na metade
      leve porque é dela que nasce a afirmação legal do guia. */
  respostaCurta: string;
  /** Chaves de `LEGAL_SOURCES` que fundamentam a matéria do guia. */
  baseLegal: string[];
  /** `baseLegal` mais os portais oficiais. É esta a lista que a página
      mostra e de que sai a contagem «{n} fontes oficiais». */
  fontesOficiais: string[];
  /** Chaves de `LEITURAS_COMPLEMENTARES`. Explicam, não fundamentam. */
  leituraComplementar: string[];
}

